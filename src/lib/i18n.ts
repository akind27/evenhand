const STRINGS: Record<Lang, Strings> = { en, el, de, it, fr };

/** Every key the renter screens use. */
export const RENTER_KEYS = Object.keys(en) as RenterKey[];

/** The text for a key in a language. */
export function t(lang: Lang, key: RenterKey): string {
  return STRINGS[lang][key];
}

/** Like `t`, with {placeholders} filled in. */
export function tf(lang: Lang, key: RenterKey, values: Record<string, string>): string {
  return t(lang, key).replace(/\{(\w+)\}/g, (whole, name: string) => values[name] ?? whole);
}

/** The browser language when it is one of ours, otherwise English. */
export function detectLang(browserLanguage: string | undefined): Lang {
  const code = (browserLanguage ?? '').slice(0, 2).toLowerCase();
  return (LANGS as readonly string[]).includes(code) ? (code as Lang) : 'en';
}
